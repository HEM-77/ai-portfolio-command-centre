// ---------------------------------------------------------------------------
// §1 Response envelope and error codes
// ---------------------------------------------------------------------------

export type ErrorCode =
  | "VALIDATION_ERROR"
  | "NOT_FOUND"
  | "UPSTREAM_ERROR"
  | "NOT_READY"
  | "INTERNAL_ERROR";

export interface ApiSuccess<T> {
  ok: true;
  data: T;
}

export interface ApiFailure {
  ok: false;
  error: {
    code: ErrorCode;
    message: string;
  };
}

export type ApiResponse<T> = ApiSuccess<T> | ApiFailure;

// ---------------------------------------------------------------------------
// §2 Portfolio types (produced by the Portfolio module)
// ---------------------------------------------------------------------------

/** Verbatim `initiative_type` values of the Nimbus dataset (contract §5.2, §8 #13). */
export type InitiativeType = "Copilot" | "Conversational Bot" | "Predictive Model" | "AI-enabled Automation";
export type InitiativeStatus = "on_track" | "at_risk" | "off_track";

/** One row of the portfolio scorecard. All numbers are calculated by the Portfolio module. */
export interface InitiativeMetrics {
  initiativeId: string; // "NMB-001"
  name: string;
  businessUnit: string;
  owner: string | null; // no dataset column (contract §8 #13): null until sourced from the charter
  initiativeType: InitiativeType; // from initiatives.csv initiative_type (replaces `stage`, §8 #13)
  status: InitiativeStatus; // derived by rule, see contract §5.4
  spendToDate: number;
  valueRealised: number;
  roi: number | null; // (valueRealised - spendToDate) / spendToDate; null if spend is 0
  adoptionRate: number | null; // weekly active users / licensed users in the latest week
  paybackMonths: number | null; // null if not yet paying back
  dataQualityIssueCount: number;
  asOf: string; // ISO date of the latest data point
}

export interface PortfolioSummary {
  asOf: string;
  initiativeCount: number;
  totalSpend: number;
  totalValueRealised: number;
  portfolioRoi: number | null;
  averageAdoptionRate: number | null;
  negativeRoiCount: number;
  countsByStatus: Record<InitiativeStatus, number>;
}

export interface Scorecard {
  summary: PortfolioSummary;
  initiatives: InitiativeMetrics[];
}

export interface DataQualityIssue {
  issueId: string; // "DQ-0001"
  sourceFile: string; // "data/initiatives.csv"
  row: number | null; // 1-based data row, null for file-level issues
  initiativeId: string | null;
  field: string | null;
  severity: "error" | "warning";
  action: "rejected" | "repaired" | "flagged";
  message: string;
}

export interface DataQualityReport {
  generatedAt: string;
  rowsRead: number;
  rowsAccepted: number;
  rowsRejected: number;
  issues: DataQualityIssue[];
}

// ---------------------------------------------------------------------------
// §2 RAG and assistant types
// ---------------------------------------------------------------------------

/** One retrieved charter chunk. Returned by the RAG module. */
export interface Evidence {
  chunkId: string; // "INIT-003#risks-2"
  initiativeId: string;
  sourceFile: string; // "charters/INIT-003-claims-triage.md"
  section: string; // heading the chunk came from, e.g. "Risks"
  text: string;
  score: number; // similarity, 0..1, higher is better
}

export type QuestionType = "numerical" | "narrative" | "mixed";
export type ValidationStatus = "verified" | "unverified" | "insufficient_evidence";

export interface Figure {
  initiativeId: string | null; // null for portfolio-level figures
  metric: string; // must be a field name of InitiativeMetrics or PortfolioSummary
  value: number | null;
  source: "scorecard"; // figures always come from the scorecard, never the LLM
}

export interface Citation {
  citationId: string; // "C1", referenced in the answer text as [C1]
  initiativeId: string;
  sourceFile: string;
  section: string;
  excerpt: string; // short quote from Evidence.text
}

// ---------------------------------------------------------------------------
// §2 Reporting types
// ---------------------------------------------------------------------------

export type AttentionFlagRule = "negative_roi" | "low_adoption" | "long_payback" | "data_quality";
export type AttentionFlagSeverity = "high" | "medium" | "low";

export interface AttentionFlag {
  flagId: string; // "FLAG-001"
  initiativeId: string;
  initiativeName: string;
  rule: AttentionFlagRule;
  severity: AttentionFlagSeverity;
  message: string; // plain-English, generated by code, not the LLM
  metrics: Partial<InitiativeMetrics>;
}

