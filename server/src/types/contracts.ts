/** §3.1 GET /api/health */
export interface HealthStatus {
  status: "ok" | "degraded"; // "degraded" when any check is false; still HTTP 200
  uptimeSeconds: number;
  checks: {
    scorecardLoaded: boolean;
    initiativeCount: number;
    vectorIndexLoaded: boolean;
    chunkCount: number;
    openRouterConfigured: boolean;
    embeddingConfigured: boolean;
  };
}

/** §3.2 GET /api/portfolio/summary returns PortfolioSummary. */

/**
 * §3.3 GET /api/portfolio/initiatives query parameters (PROPOSED). Identical to the service
 * filter: the controller validates them and passes them straight to getInitiatives().
 */
export type InitiativesQuery = InitiativeFilter;

/** §3.3 GET /api/portfolio/initiatives */
export interface InitiativesResponse {
  asOf: string;
  initiatives: InitiativeMetrics[];
}

/** §3.4 GET /api/portfolio/quality returns DataQualityReport. */

/** §3.5 POST /api/assistant/ask request body. */
export interface AskRequest {
  question: string; // required, 3–1000 characters after trimming
  initiativeIds?: string[]; // optional, known initiative IDs only
}

/** §3.5 POST /api/assistant/ask response data. */
export interface AskResult {
  questionType: QuestionType;
  answer: string;
  figures: Figure[];
  citations: Citation[];
  validation: {
    status: ValidationStatus;
    notes: string[];
  };
  model: string | null; // OpenRouter model ID; null when no LLM was called
  generatedAt: string; // ISO timestamp
}

/** §3.6 narrative status: ValidationStatus plus "unavailable" when the LLM call fails. */
export type NarrativeStatus = ValidationStatus | "unavailable";

export interface WeeklyBriefNarrative {
  status: NarrativeStatus;
  text: string | null; // null when status is "unavailable"
  citations: Citation[];
}

/** §3.6 GET /api/reports/weekly */
export interface WeeklyBrief {
  weekEnding: string; // ISO date, latest asOf in the data (contract §8 #11)
  generatedAt: string;
  summary: PortfolioSummary;
  flags: AttentionFlag[];
  narrative: WeeklyBriefNarrative;
}

// ---------------------------------------------------------------------------
// §4 Service-level contracts. Each module's index.ts exports an object that
// implements one of these. Other modules import only that object.
// ---------------------------------------------------------------------------

export interface InitiativeFilter {
  status?: InitiativeStatus;
  businessUnit?: string;
  sort?: keyof InitiativeMetrics; // default "initiativeId"
  order?: "asc" | "desc"; // default "asc"; null values always sort last
}

/** server/src/services/portfolio/index.ts — Spoorthy */
export interface PortfolioService {
  load(): Promise<void>; // read CSV, validate, normalise, calculate (on startup)
  isReady(): boolean;
  getScorecard(): Scorecard; // validated, calculated data only
  getSummary(): PortfolioSummary;
  getInitiatives(filter?: InitiativeFilter): InitiativeMetrics[]; // filters and sorts
  getInitiative(initiativeId: string): InitiativeMetrics | undefined;
  getQualityReport(): DataQualityReport;
}

export interface RetrieveOptions {
  initiativeIds?: string[]; // restrict to these initiatives
  topK?: number; // default 5
  minScore?: number; // drop weak matches
}

/** server/src/services/rag/index.ts — Hem */
export interface RagService {
  buildIndex(): Promise<{ chunkCount: number }>; // charters -> chunks -> embeddings -> JSON index
  loadIndex(): Promise<void>; // on startup
  isReady(): boolean;
  getChunkCount(): number; // chunks in the loaded index; 0 when not loaded (for /api/health)
  retrieve(query: string, options?: RetrieveOptions): Promise<Evidence[]>; // [] when nothing relevant
}

export interface NarrativeInput {
  purpose: "weekly_brief";
  summary: PortfolioSummary;
  flags: AttentionFlag[];
}

/** server/src/services/ai/index.ts — Hem */
export interface AiService {
  ask(input: AskRequest): Promise<AskResult>;
  generateNarrative(input: NarrativeInput): Promise<WeeklyBriefNarrative>;
}

/** server/src/services/reporting/index.ts — Animesh */
export interface ReportingService {
  getAttentionFlags(): AttentionFlag[]; // pure rules over the scorecard, no LLM
  getWeeklyBrief(): Promise<WeeklyBrief>;
}
